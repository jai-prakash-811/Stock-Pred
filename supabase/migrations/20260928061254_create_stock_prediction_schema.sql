/*
# Stock Market Prediction App Schema

## Overview
Single-tenant (no auth) schema for a stock market prediction application.
Stores a universe of stocks with simulated price data, user watchlists,
and prediction history generated by the built-in prediction engine.

## Tables

### stocks
- `id` (uuid, primary key)
- `symbol` (text, unique, not null) — e.g. "AAPL"
- `name` (text, not null) — company name
- `sector` (text) — e.g. "Technology"
- `current_price` (numeric) — latest simulated price
- `price_change` (numeric) — day's change in dollars
- `price_change_pct` (numeric) — day's change in percent
- `volume` (bigint) — simulated daily volume
- `market_cap` (numeric) — simulated market cap in billions
- `pe_ratio` (numeric) — simulated P/E ratio
- `dividend_yield` (numeric) — simulated dividend yield
- `beta` (numeric) — simulated beta coefficient
- `price_history` (jsonb) — array of 90 daily price objects {date, open, high, low, close, volume}
- `updated_at` (timestamptz) — last data refresh

### watchlist
- `id` (uuid, primary key)
- `symbol` (text, not null) — stock symbol to watch
- `added_at` (timestamptz)

### predictions
- `id` (uuid, primary key)
- `symbol` (text, not null) — stock symbol predicted
- `predicted_price` (numeric) — forecasted price
- `predicted_change_pct` (numeric) — forecasted percent change
- `direction` (text) — "bullish" or "bearish"
- `confidence` (numeric) — 0–100 confidence score
- `method` (text) — prediction method used
- `horizon_days` (int) — prediction horizon in days
- `indicators` (jsonb) — technical indicators at time of prediction
- `created_at` (timestamptz)

## Security
- RLS enabled on all tables.
- All tables allow anon + authenticated CRUD (single-tenant, intentionally shared data).
*/

CREATE TABLE IF NOT EXISTS stocks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  symbol text UNIQUE NOT NULL,
  name text NOT NULL,
  sector text,
  current_price numeric NOT NULL DEFAULT 0,
  price_change numeric NOT NULL DEFAULT 0,
  price_change_pct numeric NOT NULL DEFAULT 0,
  volume bigint NOT NULL DEFAULT 0,
  market_cap numeric NOT NULL DEFAULT 0,
  pe_ratio numeric,
  dividend_yield numeric,
  beta numeric,
  price_history jsonb NOT NULL DEFAULT '[]'::jsonb,
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE stocks ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "anon_select_stocks" ON stocks;
CREATE POLICY "anon_select_stocks" ON stocks FOR SELECT
  TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "anon_insert_stocks" ON stocks;
CREATE POLICY "anon_insert_stocks" ON stocks FOR INSERT
  TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_update_stocks" ON stocks;
CREATE POLICY "anon_update_stocks" ON stocks FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_stocks" ON stocks;
CREATE POLICY "anon_delete_stocks" ON stocks FOR DELETE
  TO anon, authenticated USING (true);

CREATE TABLE IF NOT EXISTS watchlist (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  symbol text UNIQUE NOT NULL,
  added_at timestamptz DEFAULT now()
);

ALTER TABLE watchlist ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "anon_select_watchlist" ON watchlist;
CREATE POLICY "anon_select_watchlist" ON watchlist FOR SELECT
  TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "anon_insert_watchlist" ON watchlist;
CREATE POLICY "anon_insert_watchlist" ON watchlist FOR INSERT
  TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_watchlist" ON watchlist;
CREATE POLICY "anon_delete_watchlist" ON watchlist FOR DELETE
  TO anon, authenticated USING (true);

CREATE TABLE IF NOT EXISTS predictions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  symbol text NOT NULL,
  predicted_price numeric NOT NULL,
  predicted_change_pct numeric NOT NULL,
  direction text NOT NULL,
  confidence numeric NOT NULL,
  method text NOT NULL,
  horizon_days int NOT NULL DEFAULT 7,
  indicators jsonb,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE predictions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "anon_select_predictions" ON predictions;
CREATE POLICY "anon_select_predictions" ON predictions FOR SELECT
  TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "anon_insert_predictions" ON predictions;
CREATE POLICY "anon_insert_predictions" ON predictions FOR INSERT
  TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_predictions" ON predictions;
CREATE POLICY "anon_delete_predictions" ON predictions FOR DELETE
  TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS idx_watchlist_symbol ON watchlist(symbol);
CREATE INDEX IF NOT EXISTS idx_predictions_symbol ON predictions(symbol);
CREATE INDEX IF NOT EXISTS idx_predictions_created ON predictions(created_at DESC);